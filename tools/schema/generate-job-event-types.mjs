import { readFile, writeFile } from "node:fs/promises";
import process from "node:process";
import { URL, fileURLToPath } from "node:url";
import path from "node:path";
import ts from "typescript";
import prettier from "prettier";

const root = fileURLToPath(new URL("../../", import.meta.url));
const names = new Set(["JOB_PROGRESS_STAGES", "JobProgressStage", "JobEventBase", "JobEvent"]);
const printer = ts.createPrinter();
function select(source, allowed) {
  const file = ts.createSourceFile("contract.ts", source, ts.ScriptTarget.Latest, true);
  return file.statements
    .filter((node) => {
      const name = ts.isVariableStatement(node)
        ? node.declarationList.declarations[0]?.name.getText(file)
        : node.name?.getText(file);
      return allowed.has(name);
    })
    .map((node) => printer.printNode(ts.EmitHint.Unspecified, node, file))
    .join("\n");
}
const statuses = select(
  await readFile(path.join(root, "packages/domain/src/modules/jobs/job.ts"), "utf8"),
  new Set(["JobStatus"]),
);
const events = select(
  await readFile(path.join(root, "packages/domain/src/modules/jobs/job-events.ts"), "utf8"),
  names,
);
const output = await prettier.format(
  `// Generated by tools/schema/generate-job-event-types.mjs. Do not edit.\n${statuses}\n${events}\n`,
  { parser: "typescript", printWidth: 100 },
);
const target = path.join(root, "packages/schemas/src/job-event.generated.ts");
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== output)
    throw new Error(
      "Job event consumer types are stale. Run node tools/schema/generate-job-event-types.mjs.",
    );
} else await writeFile(target, output);
