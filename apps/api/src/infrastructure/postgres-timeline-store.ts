import type { Pool } from "pg";
import { Timeline, uuidV7, type UserId } from "@editagent/domain";
import { contentHash } from "@editagent/tool-sdk";
import type { TimelineStore, StoredTimeline } from "../application/timeline-editor.js";
import { TimelineConflict } from "../application/timeline-editor.js";
import { ProjectNotFoundError } from "../application/project-access.js";

/** Adapter for the existing migration-0018 snapshot/CAS contract. */
export class PostgresTimelineStore implements TimelineStore {
  constructor(private readonly pool: Pick<Pool, "query">) {}

  async load(project: string, id: string): Promise<StoredTimeline> {
    uuidV7(project);
    uuidV7(id);
    const result = await this.pool.query<{ snapshot: unknown; state_sha256: string }>(
      `SELECT t.snapshot,t.state_sha256 FROM editing_timelines t
       JOIN projects p ON p.id=t.project_id
       WHERE t.id=$1 AND t.project_id=$2 AND p.deleted_at IS NULL`,
      [id, project],
    );
    const row = result.rows[0];
    if (!row || contentHash(row.snapshot) !== row.state_sha256) throw new ProjectNotFoundError();
    const timeline = Timeline.restore(row.snapshot);
    if (timeline.id !== id || timeline.projectId !== project) throw new ProjectNotFoundError();
    return { timeline, stateSha256: row.state_sha256 };
  }

  async save(actor: UserId, timeline: Timeline, expectedSha256: string | null): Promise<string> {
    const snapshot = Timeline.restore(timeline.toSnapshot()).toSnapshot();
    const hash = contentHash(snapshot);
    // Share locks keep membership revocation/project deletion ordered with this write.
    // The immutable input is generated by the application, never a caller snapshot.
    const permission = `WITH permitted AS MATERIALIZED (
      SELECT p.id FROM projects p JOIN project_memberships m ON m.project_id=p.id
      WHERE p.id=$2 AND p.deleted_at IS NULL AND m.user_id=$5
        AND m.role IN ('owner','editor') FOR SHARE OF p,m)`;
    const result =
      expectedSha256 === null
        ? await this.pool.query(
            `${permission}
          INSERT INTO editing_timelines(id,project_id,snapshot,state_sha256)
          SELECT $1,id,$3::jsonb,$4 FROM permitted ON CONFLICT DO NOTHING`,
            [timeline.id, timeline.projectId, JSON.stringify(snapshot), hash, actor],
          )
        : await this.pool.query(
            `${permission}
          UPDATE editing_timelines t SET snapshot=$3::jsonb,state_sha256=$4
          FROM permitted p WHERE t.id=$1 AND t.project_id=p.id AND t.state_sha256=$6`,
            [
              timeline.id,
              timeline.projectId,
              JSON.stringify(snapshot),
              hash,
              actor,
              expectedSha256,
            ],
          );
    if (result.rowCount !== 1) throw new TimelineConflict();
    return hash;
  }
}
